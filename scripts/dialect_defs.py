SIGN_MARKERS = ("手语", "sign language", "台湾手语")

# Opera/theater (NOT a language dialect per se)
OPERA_MARKERS = ("京剧电影", "戏曲", "黄梅戏", "曲剧")


def normalize_text(v):
    if pd.isna(v):
        return ""
    return re.sub(r"\s+", " ", str(v).strip()).casefold()


def lang_parts(v):
    text = normalize_text(v)
    if not text:
        return []
    return [p.strip() for p in re.split(r"\s*(?:/|\||;|；|,)\s*", text) if p.strip()]


def marker_matches_part(marker, part_norm):
    """短拉丁标记精确匹配，其余子串匹配。"""
    mnorm = normalize_text(marker)
    if marker in SHORT_LATIN_MARKERS:
        return mnorm == part_norm  # 精确匹配
    return mnorm in part_norm       # 子串匹配


def has_strict_dialect_tag(lang):
    """语言字段是否含中国方言/少数民族语言标签（v2.1 核心判定，无间接规则）。

    F5 治理（2026-08-15）：短拉丁标记（≤3 字符）改用逐 part 精确匹配，
    防止 "dai" 等子串误命中英文单词。
    """
    for p in lang_parts(lang):
        pnorm = normalize_text(p)
        for marker in DIALECT_MARKERS_STRICT:
            if marker_matches_part(marker, pnorm):
                return True
    return False


def has_mandarin_tag(lang):
    """语言字段是否含普通话标签。

    ⚠️ 方言优先完成式（2026-08-15 F1 收尾）：逐 part 判定，含方言白名单
    子串的 part（如"汉语方言"含"汉语"、"中文方言"含"中文"、"汉语（甘肃方言）"
    含"汉语"）不贡献普通话信号——否则仅标通用方言标签的影片被误判为
    含普通话（Tier 1 误入 Tier 2）。若字段中另有独立的普通话 part
    （如"汉语普通话"）则不受影响。
    """
    for p in lang_parts(lang):
        pnorm = normalize_text(p)
        if any(marker_matches_part(m, pnorm) for m in DIALECT_MARKERS_STRICT):
            continue  # 方言优先：该 part 不算普通话信号
        if any(m in pnorm for m in MANDARIN_MARKERS):
            return True
    return False


def has_foreign_tag(lang):
    text = normalize_text(lang)
    return any(marker_matches_part(m, text) for m in FOREIGN_MARKERS)


def first_tag_is_foreign(lang):
    """方案 A 判定（2026-08-15）：语言字段首个标签（归一化后）是否命中外语标记。

    用于排除"外语对白为主、方言点缀"的中国制片方言片：
    Region == "China" 且命中方言标签、但首个语言标签为外语时，
    不计入方言口径（Is_Dialect=0）。规则出处：analyze_v21_foreign_risk.py
    四方案模拟后选定的方案 A（最保守精准），落地脚本 scripts/history/apply_plan_a.py
    （判定已内置 data_processor.language_code / first_tag_is_foreign）。
    仅判定标签结构，不改变白名单本身；调用方需自行限定 Region == "China"。
    """
    parts = lang_parts(lang)
    if not parts:
        return False
    p0 = normalize_text(parts[0])
    return any(marker_matches_part(m, p0) for m in FOREIGN_MARKERS)


def has_minority_tag(lang):
    text = normalize_text(lang)
    return any(marker_matches_part(m, text) for m in MINORITY_MARKERS)


def normalize_language_tags(lang):
    """归一化语言字段中的普通话/国语标签。

    数据新闻研究口径：
    - "国语"是普通话的历史称谓与台湾地区的常用称谓，本质上属于现代标准汉语；
    - "台湾国语"是普通话在台湾的地域变体，仍属官话系统，不是闽南方言；
    - 为保持对照组清晰，将非台湾的"国语"归并为"普通话"，"台湾国语"单独保留。

    ⚠️ 方言优先规则（2026-08-15 F1 修复）：
    若标签同时含方言白名单子串（如"汉语方言""中文方言"含"汉语/中文"），
    保留原样不归并为"普通话"——否则方言信号在 Tier 2a 判定中被剥离，
    导致 6 部影片从 Tier 2a 误降为 Tier 2b（《血蝉》《归去来》《黄金大劫案》
    《我是路人甲》《巧巧》等）。同日 F1 收尾（见 has_mandarin_tag）：
    仅标通用方言标签的影片进一步升回 Tier 1。回归测试见 tests/test_pipeline.py。
    """
    parts = lang_parts(lang)
    result = []
    for p in parts:
        pnorm = normalize_text(p)
        is_dialect = any(marker_matches_part(m, pnorm) for m in DIALECT_MARKERS_STRICT)
        if is_dialect:
            result.append(p)  # 方言优先：不归一化为普通话
            continue
        is_mandarin = any(normalize_text(m) in pnorm for m in MANDARIN_MARKERS)
        if is_mandarin:
            if "台湾国语" in p or "臺灣國語" in p:
                result.append("台湾国语")
            else:
                result.append("普通话")
        else:
            result.append(p)
    return result


def get_dialect_tags_found(lang):
    """Return list of Chinese dialect/minority tags found in language field."""
    found = []
    parts = lang_parts(lang)
    for p in parts:
        pnorm = normalize_text(p)
        for group, markers in DIALECT_GROUPS.items():
            for marker in markers:
                if marker_matches_part(marker, pnorm):
                    found.append(p.strip())
                    break
            else:
                continue
            break
    return found
